#include "agent/ed25519.h"

#include <assert.h>
#include <stdint.h>
#include <string.h>

static void test_ed25519_rfc8032_case_1_empty_msg(void) {
  // RFC 8032 Ed25519 test vector 1:
  // secret key seed (32 bytes):
  //   9d61b19deffd5a60ba844af492ec2cc4
  //   4449c5697b326919703bac031cae7f60
  // public key:
  //   d75a980182b10ab7d54bfed3c964073a
  //   0ee172f3daa62325af021a68f707511a
  // message: empty
  // signature:
  //   e5564300c360ac729086e2cc806e828a
  //   84877f1eb8e5d974d873e06522490155
  //   5fb8821590a33bacc61e39701cf9b46b
  //   d25bf5f0595bbe24655141438e7a100b

  const uint8_t sk[32] = {
    0x9d, 0x61, 0xb1, 0x9d, 0xef, 0xfd, 0x5a, 0x60,
    0xba, 0x84, 0x4a, 0xf4, 0x92, 0xec, 0x2c, 0xc4,
    0x44, 0x49, 0xc5, 0x69, 0x7b, 0x32, 0x69, 0x19,
    0x70, 0x3b, 0xac, 0x03, 0x1c, 0xae, 0x7f, 0x60,
  };
  const uint8_t pk_expect[32] = {
    0xd7, 0x5a, 0x98, 0x01, 0x82, 0xb1, 0x0a, 0xb7,
    0xd5, 0x4b, 0xfe, 0xd3, 0xc9, 0x64, 0x07, 0x3a,
    0x0e, 0xe1, 0x72, 0xf3, 0xda, 0xa6, 0x23, 0x25,
    0xaf, 0x02, 0x1a, 0x68, 0xf7, 0x07, 0x51, 0x1a,
  };
  const uint8_t sig_expect[64] = {
    0xe5, 0x56, 0x43, 0x00, 0xc3, 0x60, 0xac, 0x72,
    0x90, 0x86, 0xe2, 0xcc, 0x80, 0x6e, 0x82, 0x8a,
    0x84, 0x87, 0x7f, 0x1e, 0xb8, 0xe5, 0xd9, 0x74,
    0xd8, 0x73, 0xe0, 0x65, 0x22, 0x49, 0x01, 0x55,
    0x5f, 0xb8, 0x82, 0x15, 0x90, 0xa3, 0x3b, 0xac,
    0xc6, 0x1e, 0x39, 0x70, 0x1c, 0xf9, 0xb4, 0x6b,
    0xd2, 0x5b, 0xf5, 0xf0, 0x59, 0x5b, 0xbe, 0x24,
    0x65, 0x51, 0x41, 0x43, 0x8e, 0x7a, 0x10, 0x0b,
  };

  uint8_t pk[32];
  memset(pk, 0, sizeof(pk));
  agent_ed25519_publickey(sk, pk);
  assert(memcmp(pk, pk_expect, sizeof(pk_expect)) == 0);

  uint8_t sig[64];
  memset(sig, 0, sizeof(sig));
  agent_ed25519_sign(/*msg=*/NULL, /*msg_len=*/0, sk, pk, sig);
  assert(memcmp(sig, sig_expect, sizeof(sig_expect)) == 0);

  assert(agent_ed25519_verify(/*msg=*/NULL, /*msg_len=*/0, pk, sig) == 1);

  // Basic negative check (flip 1 bit).
  sig[0] ^= 0x01;
  assert(agent_ed25519_verify(/*msg=*/NULL, /*msg_len=*/0, pk, sig) == 0);
}

void test_ed25519_module(void) {
  test_ed25519_rfc8032_case_1_empty_msg();
}

