import {test,expect} from "@playwright/test";
import {createServer} from "node:net";
import {execFileSync} from "node:child_process";
test("guided integration read preserves settings and executes exact saved SOP",async({page})=>{
 const socket=createServer();await new Promise<void>(r=>socket.listen(0,"127.0.0.1",r));
 const port=(socket.address() as any).port;await new Promise<void>(r=>socket.close(()=>r()));
 let submitted:any;
 await page.addInitScript(()=>{localStorage.setItem("agentui.connectionMode",JSON.stringify("direct"));localStorage.setItem("agentui.base","http://127.0.0.1:7777");localStorage.setItem("agentui.showSettings","false");});
 await page.route("**/api/v1/**",r=>r.fulfill({json:{ok:true,features:{},sessions:[],tools:[],messages:[],runs:[],events:[],workflows:[],schedules:[],prefs:{}}}));
 await page.route("**/api/v1/workflow/submit",r=>{submitted=r.request().postDataJSON();return r.fulfill({json:{ok:true,workflow_id:"http-authored"}});});
 await page.goto("/");await page.getByRole("navigation").getByRole("button",{name:"Workflows",exact:true}).click();
 await page.getByRole("button",{name:"Create workflow",exact:true}).click();
 await page.getByRole("combobox",{name:"Workflow template",exact:true}).selectOption("sop");
 await page.getByLabel("Add action",{exact:true}).first().selectOption("http_json");
 await expect(page.getByRole("alert").filter({hasText:"Enter an HTTP"})).toBeVisible();
 await page.getByLabel("Integration URL",{exact:true}).fill("http://127.0.0.1:"+port+"/status");
 await page.getByLabel("Bearer credential environment name",{exact:true}).fill("SOP_TEST_TOKEN");
 await page.getByLabel("Request timeout (milliseconds)",{exact:true}).fill("4500");
 await page.getByLabel("Response limit (bytes)",{exact:true}).fill("4096");
 await page.getByText("Advanced process configuration",{exact:true}).click();
 const raw=page.getByTestId("workflow-composer-json");let draft=JSON.parse(await raw.inputValue());
 const action=draft.sop.stages[0].actions.find((a:any)=>a.kind==="http_json");
 action.http_json.headers={"X-Test":"preserved"};action.max_attempts=1;
 await raw.fill(JSON.stringify(draft));
 await page.getByLabel("Integration URL",{exact:true}).fill("http://127.0.0.1:"+port+"/status");
 draft=JSON.parse(await raw.inputValue());expect(draft.sop.stages[0].actions.find((a:any)=>a.kind==="http_json").http_json.headers).toEqual({"X-Test":"preserved"});
 await page.setViewportSize({width:320,height:800});expect(await page.locator("#workspace-main").evaluate(e=>e.scrollWidth<=e.clientWidth)).toBe(true);
 // Existing POST/effect settings must never be coerced into a GET.
 const readDraft=await raw.inputValue();
 const postDraft=JSON.parse(readDraft),postAction=postDraft.sop.stages[0].actions.find((a:any)=>a.kind==="http_json");
 postAction.http_json={method:"POST",url:"https://example.invalid/write",body:{keep:true},effect:{mode:"guarded"}};
 const exactPost=JSON.stringify(postAction);
 await raw.fill(JSON.stringify(postDraft));
 await expect(page.getByLabel("Integration URL",{exact:true})).toHaveCount(0);
 await page.getByLabel("Process name",{exact:true}).fill("Preserve advanced integration");
 expect(JSON.stringify(JSON.parse(await raw.inputValue()).sop.stages[0].actions.find((a:any)=>a.kind==="http_json"))).toBe(exactPost);
 await raw.fill(readDraft);
 expect(submitted).toBeUndefined();
 await page.getByRole("button",{name:"Submit workflow",exact:true}).click();
 await expect.poll(()=>!!submitted).toBe(true);
 const output=execFileSync("python3",["../tests/workflow_authored_http_smoke.py","../build/agentd"],{input:JSON.stringify(submitted),encoding:"utf8",timeout:45000});
 expect(output).toContain("PASS exact browser-authored GET SOP");
});
